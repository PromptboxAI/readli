// Archives every version of every book's text the app has ever built, so narration prepared from
// an older text can always be played and read along with exactly the words it says.
//
//   node scripts/revisions/archive.mjs
//
// Walks every commit (main and other branches, since preview deployments can prepare narration too)
// that could change a book's text, builds each book there with that commit's own code, and writes
// src/lib/library/revisions/manifest.json plus one snapshot per revision that isn't today's text.
// Run it in the same PR as any change to a book's text; the revisions test fails until you do.
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const repo = execFileSync("git", ["rev-parse", "--show-toplevel"]).toString().trim();
const out = join(repo, "src/lib/library/revisions");
const paths = ["src/lib/library", "src/lib/content/demo-books.ts", "src/lib/content/sentences.ts", "src/lib/narration/text.ts", "src/lib/content/the-end.ts"];
const git = (...args) => execFileSync("git", args, { cwd: repo, maxBuffer: 1 << 30 }).toString();
const onMain = new Set(git("rev-list", "origin/main").split("\n").filter(Boolean));
const commits = git("rev-list", "--all", "--reverse", "--format=%H %cI", "--", ...paths)
  .split("\n")
  .filter((l) => l && !l.startsWith("commit "))
  .map((l) => {
    const [sha, at] = l.split(" ");
    return { sha, at };
  });

function evaluate(root) {
  const json = execFileSync(process.execPath, ["--no-warnings", join(repo, "scripts/revisions/eval.mjs")], {
    env: { ...process.env, REVISIONS_ROOT: root },
    maxBuffer: 1 << 30,
  }).toString();
  return JSON.parse(json);
}

const seen = new Map();
const failed = [];
const note = (book, commit, published) => {
  const key = `${book.slug}:${book.revision}`;
  const was = seen.get(key);
  if (was) {
    // Chapter titles, the book title and where a story is split into parts aren't narrated and can
    // change within a revision; the sentences can't.
    const words = (b) => JSON.stringify(b.chapters.flatMap((c) => c.sentences));
    if (words(was.book) !== words(book) || was.book.edition !== book.edition) throw new Error(`${key} built two different texts`);
    was.book = { ...book };
    was.lastSeen = commit.at > was.lastSeen ? commit.at : was.lastSeen;
    was.firstSeen = commit.at < was.firstSeen ? commit.at : was.firstSeen;
    was.published ||= published;
  } else seen.set(key, { book, firstSeen: commit.at, lastSeen: commit.at, published });
};

for (const commit of commits) {
  if (!git("ls-tree", "-r", "--name-only", commit.sha, "src/lib/narration/text.ts").trim()) continue;
  const dir = mkdtempSync(join(tmpdir(), "readli-rev-"));
  try {
    execFileSync("sh", ["-c", `git archive ${commit.sha} src | tar -x -C ${dir}`], { cwd: repo });
    for (const book of evaluate(dir)) note(book, commit, onMain.has(commit.sha));
  } catch (err) {
    failed.push(`${commit.sha.slice(0, 7)}: ${String(err.message).split("\n")[0]}`);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}
// Today's text, including uncommitted edits.
const current = new Map(evaluate(repo).map((b) => [b.slug, b]));
for (const book of current.values()) note(book, { at: new Date().toISOString() }, true);

const previous = existsSync(join(out, "manifest.json")) ? JSON.parse(readFileSync(join(out, "manifest.json"), "utf8")) : {};
const corrections = new Set(Object.values(previous).flat().filter((r) => r.correction).map((r) => `${r.slug}:${r.revision}`));
const manifest = {};
mkdirSync(join(out, "snapshots"), { recursive: true });
for (const { book, firstSeen, lastSeen, published } of [...seen.values()].sort((a, b) => a.firstSeen.localeCompare(b.firstSeen))) {
  const isCurrent = current.get(book.slug)?.revision === book.revision;
  (manifest[book.slug] ??= []).push({
    slug: book.slug,
    revision: book.revision,
    edition: book.edition,
    firstSeen,
    lastSeen: isCurrent ? null : lastSeen,
    published,
    current: isCurrent,
    sentences: book.chapters.reduce((n, c) => n + c.sentences.length, 0),
    ...(corrections.has(`${book.slug}:${book.revision}`) ? { correction: true } : {}),
  });
  if (!isCurrent) writeFileSync(join(out, "snapshots", `${book.slug}.${book.revision}.json`), `${JSON.stringify(book, null, 1)}\n`);
}
writeFileSync(join(out, "manifest.json"), `${JSON.stringify(manifest, null, 1)}\n`);
const files = Object.values(manifest).flat().filter((r) => !r.current).map((r) => `${r.slug}.${r.revision}`);
writeFileSync(
  join(out, "snapshots.ts"),
  [
    "// Generated by scripts/revisions/archive.mjs. Every book text the app built before today's, by slug and revision.",
    'import type { RevisionSnapshot } from "./index";',
    ...files.map((f, i) => `import s${i} from "./snapshots/${f}.json";`),
    "",
    "export const SNAPSHOTS: Record<string, RevisionSnapshot> = {",
    ...files.map((f, i) => `  "${f.replace(".", ":")}": s${i},`),
    "};",
    "",
  ].join("\n"),
);
console.log(`${seen.size} revisions across ${Object.keys(manifest).length} books from ${commits.length} commits.`);
if (failed.length) {
  console.log(`Couldn't build ${failed.length} commit(s); check none of them changed a book's text:\n${failed.join("\n")}`);
  process.exitCode = 1;
}
